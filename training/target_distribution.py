"""Create the appendix table from the training files used by the main runs.

Run from the repository root:
    uv run --locked python -m training.target_distribution
"""
import argparse
from collections import Counter
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = (("lfm", "LFM"), ("ministral", "Ministral"), ("qwen", "Qwen"), ("gemma", "Gemma"))
VITAL_LEVELS = (
    ("DAY", "Day"), ("MONTH", "Month"), ("YEAR", "Year"),
    ("DECADE", "Decade"), ("CENTURY", "Century"),
    ("CITY", "City"), ("REGION", "Region"),
    ("COUNTRY", "Country"), ("CONTINENT", "Continent"), ("IDK", "IDK"),
)
GRANOLA_LEVELS = (
    ("GRANOLA_1", "Level 1 (finest)"), ("GRANOLA_2", "Level 2"),
    ("GRANOLA_2_5", "Level 2.5"), ("GRANOLA_3", "Level 3"),
    ("GRANOLA_4", "Level 4 (coarsest)"),
)


def count_targets(path, allowed_levels):
    """Collapse realizations, refusing inconsistent targets for the same case."""
    cases = {}
    with path.open() as handle:
        for line in handle:
            row = json.loads(line)
            if row["split"] != "train":
                raise ValueError(f"Non-training row in {path}")
            key = row["qid"], row["relation"]
            level = "IDK" if row["is_idk"] else row["primary_target_level"]
            if level not in allowed_levels:
                raise ValueError(f"Unexpected target level {level!r} in {path}")
            if key in cases and cases[key] != level:
                raise ValueError(f"Conflicting targets for {key} in {path}")
            cases[key] = level
    return Counter(cases.values())


def make_table():
    counts = {"vital": {}, "granola": {}}
    for model, _ in MODELS:
        config = json.loads((ROOT / "training" / "configs" / f"{model}.json").read_text())
        for source, field, levels in (
            ("vital", "data_dir", VITAL_LEVELS),
            ("granola", "granola_data_dir", GRANOLA_LEVELS),
        ):
            path = ROOT / config[field] / "train.jsonl"
            counts[source][model] = count_targets(path, {key for key, _ in levels})

    def row(label, values, bold=False):
        cells = [label, *(f"{value:,}" for value in values)]
        if bold:
            cells = [rf"\textbf{{{cell}}}" for cell in cells]
        return " & ".join(cells) + r" \\"

    lines = [
        "% Generated by: uv run --locked python -m training.target_distribution",
        r"\begin{table}[t]", r"\small", r"\centering",
        r"\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{@{}lrrrr@{}}",
        r"\toprule", "Target granularity & " + " & ".join(name for _, name in MODELS) + r" \\",
    ]
    totals = {}
    for source, title, levels in (
        ("vital", "Vital Persons", VITAL_LEVELS),
        ("granola", r"\textsc{GranolaEQ}", GRANOLA_LEVELS),
    ):
        lines.extend([r"\midrule", rf"\multicolumn{{5}}{{@{{}}l}}{{\textit{{{title}}}}} \\", r"\addlinespace[2pt]"])
        for key, label in levels:
            if source == "vital" and key in {"CITY", "IDK"}:
                lines.append(r"\addlinespace[2pt]")
            lines.append(row(label, [counts[source][model][key] for model, _ in MODELS]))
        totals[source] = [sum(counts[source][model].values()) for model, _ in MODELS]
        lines.append(row("Subtotal", totals[source], bold=True))
    lines.extend([
        r"\midrule", row("Total targets", [sum(values) for values in zip(*totals.values())], bold=True),
        r"\bottomrule", r"\end{tabular}", r"\caption{",
        "Target granularity in the model-specific training splits.",
        "Each accepted QID--relation pair is counted once, irrespective of",
        "the number of response realizations. Development and test targets",
        "are excluded. Temporal targets use five levels; geographic targets",
        r"use four. \textsc{GranolaEQ} levels are relative positions normalized",
        "from 1 (finest) to 4 (coarsest); three-answer hierarchies use",
        "levels 1, 2.5, and 4. Counts describe targets, not loss weights.",
        r"}", r"\label{tab:target-granularity-distribution}", r"\end{table}",
    ])
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "training/results/target-distribution.tex")
    args = parser.parse_args()
    table = make_table()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(table)
    print(args.output)


if __name__ == "__main__":
    main()
